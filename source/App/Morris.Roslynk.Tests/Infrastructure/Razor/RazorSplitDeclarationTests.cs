	[Fact]
	public async Task WhenDeclarationsAreSplitOff_ThenBothGeneratedDocumentsBelongToTheRazorFile()
	{
		using SolutionWorkspace workspace = await SolutionWorkspace.LoadAsync(TestSolutions.Razor);
		(Solution split, string razorPath, _) = await SplitCounterAsync(workspace.Solution);

		RazorSourceDocument source = (await RazorSourceDocument.ResolveAsync(split, razorPath))!;

		Assert.Equal(2, source.Documents.Count);
		Assert.Equal("Counter_razor.g.cs", Path.GetFileName(source.Document.FilePath));
		Assert.EndsWith("Counter_razor.decl.g.cs", source.Documents[1].FilePath, StringComparison.Ordinal);
		Assert.All(source.Documents, document => Assert.True(RazorMapping.IsRazorGeneratedDocument(document)));
	}

	[Fact]
	public async Task WhenDeclarationsAreSplitOff_ThenEachPositionMapsIntoTheDocumentHoldingIt()
	{
		using SolutionWorkspace workspace = await SolutionWorkspace.LoadAsync(TestSolutions.Razor);
		(Solution split, string razorPath, _) = await SplitCounterAsync(workspace.Solution);
		RazorSourceDocument source = (await RazorSourceDocument.ResolveAsync(split, razorPath))!;
		string razorText = source.RazorText!.ToString();

		// A field declared in the @code block lives in the declaration document...
		int field = razorText.IndexOf("private int CurrentCount;", StringComparison.Ordinal) + "private int ".Length;
		RazorMappedSpan declaration = (await source.MapToDocumentAsync(new TextSpan(field, "CurrentCount".Length)))!.Value;
		Assert.EndsWith("Counter_razor.decl.g.cs", declaration.Document.FilePath, StringComparison.Ordinal);
		Assert.Equal("CurrentCount", (await declaration.Document.GetTextAsync()).ToString(declaration.Span));

		// ...and a handler wired in markup in the render-tree document.
		int handler = razorText.IndexOf("\"IncrementCount\"", StringComparison.Ordinal) + 1;
		RazorMappedSpan markup = (await source.MapToDocumentAsync(new TextSpan(handler, "IncrementCount".Length)))!.Value;
		Assert.Equal("Counter_razor.g.cs", Path.GetFileName(markup.Document.FilePath));
		Assert.Equal("IncrementCount", (await markup.Document.GetTextAsync()).ToString(markup.Span));
	}

	[Fact]
	public async Task WhenAUsingIsNeededOnlyByTheDeclarations_ThenItIsNotReportedUnnecessary()
	{
		// The render tree is fully qualified, so there every @using looks unused; [Parameter] in the declarations
		// still needs Microsoft.AspNetCore.Components. The split must remove exactly what the single document did.
		using SolutionWorkspace workspace = await SolutionWorkspace.LoadAsync(TestSolutions.Razor);
		(Solution split, string razorPath, Solution original) = await SplitCounterAsync(workspace.Solution);
		RazorSourceDocument single = (await RazorSourceDocument.ResolveAsync(original, razorPath))!;
		RazorSourceDocument source = (await RazorSourceDocument.ResolveAsync(split, razorPath))!;

		(Solution expected, int expectedRemoved) = await RazorUnusedUsings.RemoveAsync(original, single, line: null);
		(Solution updated, int removed) = await RazorUnusedUsings.RemoveAsync(split, source, line: null);

		Assert.Equal(expectedRemoved, removed);
		Assert.Equal(await RazorTextAsync(expected, razorPath), await RazorTextAsync(updated, razorPath));
		Assert.Contains("@using Microsoft.AspNetCore.Components\r\n", await RazorTextAsync(updated, razorPath), StringComparison.Ordinal);
	}

	/// <summary>
	/// Rewrites the fixture's generated Counter_razor.g.cs to the render tree only and adds the declaration
	/// document beside it, as the .NET 11 compiler emits them. Returns the split solution, the Razor path and the
	/// solution it was split from.
	/// </summary>
	private static async Task<(Solution Split, string RazorPath, Solution Original)> SplitCounterAsync(Solution solution)
	{
		Project project = solution.Projects.Single();
		TextDocument razor = project.AdditionalDocuments.Single(document => Path.GetFileName(document.FilePath) == "Counter.razor");
		string razorPath = razor.FilePath!;
		Document generated = project.Documents.Single(document => Path.GetFileName(document.FilePath) == "Counter_razor.g.cs");

		// The @code block's content (after "@code {" up to its closing brace), copied verbatim as the compiler does.
		SourceText razorText = await razor.GetTextAsync();
		int codeStart = razorText.Lines[6].Start + "@code {".Length;
		int codeEnd = razorText.Lines[21].Start;
		string code = razorText.ToString(TextSpan.FromBounds(codeStart, codeEnd));

		string renderTree = RenderTreeTemplate.Replace("{RAZOR}", razorPath, StringComparison.Ordinal);
		string declaration = DeclarationTemplate.Replace("{RAZOR}", razorPath, StringComparison.Ordinal).Replace("{CODE}\n", code, StringComparison.Ordinal).Replace("{CODE}\r\n", code, StringComparison.Ordinal);

		Solution split = solution.WithDocumentText(generated.Id, SourceText.From(renderTree));

		// Under a .NET 11 SDK the generator already split it; replace that declaration document rather than add a second.
		if (project.Documents.FirstOrDefault(document => Path.GetFileName(document.FilePath) == "Counter_razor.decl.g.cs") is Document existing)
			return (split.WithDocumentText(existing.Id, SourceText.From(declaration)), razorPath, solution);

		string declarationPath = Path.Combine(Path.GetDirectoryName(generated.FilePath!)!, "Counter_razor.decl.g.cs");
		split = split.GetProject(project.Id)!
			.AddDocument("Counter_razor.decl.g.cs", SourceText.From(declaration), generated.Folders, declarationPath)
			.Project.Solution;
		return (split, razorPath, solution);
	}

	private static async Task<string> RazorTextAsync(Solution solution, string razorPath)
	{
		DocumentId id = solution.GetDocumentIdsWithFilePath(razorPath).Single(candidate => solution.GetAdditionalDocument(candidate) is not null);
		return (await solution.GetAdditionalDocument(id)!.GetTextAsync()).ToString();
	}
}
