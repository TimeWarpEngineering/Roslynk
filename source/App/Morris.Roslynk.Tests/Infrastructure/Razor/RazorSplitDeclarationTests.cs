namespace Morris.Roslynk.Tests.Infrastructure.Razor;

/// <summary>
/// The .NET 11 Razor compiler emits each component as two documents: <c>X_razor.g.cs</c> with the render tree and
/// <c>X_razor.decl.g.cs</c> with the declarations (<c>@code</c> members). The fixtures are pinned to the .NET 10
/// SDK, whose compiler emits one document, so these tests rewrite the fixture's generated Counter into the split
/// shape (the text the .NET 11 rc compiler produced for Counter.razor) and check that the Razor seams treat both
/// documents as the Razor file's C#. Under a .NET 11 SDK the same rewrite reproduces the generator's own output.
/// </summary>
public class RazorSplitDeclarationTests
{
